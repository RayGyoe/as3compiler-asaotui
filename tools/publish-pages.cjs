// Publish the `web` arm of ui-demo/ to GitHub Pages (the `gh-pages` branch).
//
// The arm itself is built by `ui-demo/air-gallery/build.sh web` (gated by
// tools/buildsh-web.cjs + tools/mutation-buildsh-web.cjs). This script only takes
// the build it left behind and puts it where a browser can reach it:
//
//   node tools/publish-pages.cjs            stage only (prints what would ship)
//   node tools/publish-pages.cjs --serve    stage, then serve on 127.0.0.1:8123
//   node tools/publish-pages.cjs --check    fetch the live site, compare bytes
//   node tools/publish-pages.cjs --push     stage, commit on gh-pages, push
//
// Why a separate branch and not eight files under main: main's .gitignore states its
// rule out loud (inputs and unreproducible evidence go in, regenerable output does
// not), and ui-demo/air-*/ is regenerable output by definition. gh-pages is where
// GitHub serves from, so the rule survives and a clone of main keeps its size.
//
// Why the staged set and not the build directory as-is: that directory also holds
// GalleryApp.c (5.6 MB), src/ (19 staged copies of demo/*.as) and
// GalleryApp.build.json -- none of which a visitor needs to download.
'use strict';
const { execFileSync } = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const http = require('http');
const path = require('path');

const UI = path.resolve(__dirname, '..');
const SRC = path.join(UI, 'ui-demo', 'air-gallery-web');
const STAGE = path.join(UI, '.scratch', 'pages');
const BRANCH = 'gh-pages';
const SITE = 'https://raygyoe.github.io/as3compiler-asaotui/';

// index.html is what a Pages site serves at `/`; it is a byte-identical copy of the
// generated GalleryApp.html (the stage step asserts that, so the rename cannot drift).
const FILES = [
  ['GalleryApp.html', 'index.html'],
  ['GalleryApp.js', 'GalleryApp.js'],
  ['GalleryApp.wasm', 'GalleryApp.wasm'],
  ['GalleryApp.data', 'GalleryApp.data'],
  ['app.xml', 'app.xml'],
];

// The fonts ship under the name THE PAGE ASKS FOR, read out of the page itself.
//
// This used to be the hardcoded pair `fonts/arial.ttf` while the generated page said
// `fonts/Arial.ttf`. On macOS that is invisible -- the filesystem folds case, so the
// staged site worked here and 404'd there: GitHub Pages is case-sensitive, the font
// never loaded, and the published page rendered its whole layout with NO TEXT AT ALL
// (`navInk 0`; measured 2026-11-03, and it had been that way since the first publish).
// A local check cannot see this, so the name now comes from the single place that
// defines it, and the stage step proves it case-exactly.
const FONT_URLS = (() => {
  const html = fs.readFileSync(path.join(SRC, 'GalleryApp.html'), 'utf8');
  const m = /var FONT_URLS = (\[[^\]]*\]);/.exec(html);
  if (!m) return [];
  const list = JSON.parse(m[1]);
  if (!Array.isArray(list) || list.some((p) => typeof p !== 'string' || p.startsWith('/') || p.includes('..'))) {
    throw new Error('FONT_URLS in GalleryApp.html is not a list of relative paths: ' + m[1]);
  }
  return list;
})();
for (const rel of FONT_URLS) FILES.push([rel, rel]);

// Case-exact membership. `fs.existsSync` answers "yes" for `fonts/Arial.ttf` on a
// case-folding filesystem even when the entry is `arial.ttf` -- which is exactly the
// hole this file fell into. `readdir` is the only answer that survives the trip to a
// case-sensitive server.
function existsExactly(root, rel) {
  let dir = root;
  const parts = rel.split('/');
  for (let i = 0; i < parts.length; i++) {
    let names;
    try {
      names = fs.readdirSync(dir);
    } catch {
      return false;
    }
    if (!names.includes(parts[i])) return false;
    dir = path.join(dir, parts[i]);
  }
  return true;
}

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.wasm': 'application/wasm',
  '.data': 'application/octet-stream',
  '.ttf': 'font/ttf',
  '.xml': 'application/xml',
};

const GIT = { cwd: UI, encoding: 'utf8' };
function git(args, input) {
  return execFileSync('git', args, input === undefined ? GIT : { ...GIT, input }).trim();
}
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

// No page COUNT in the prose. It was "43-page" once and the site grew to 56 without
// anyone noticing here -- a number that lives in a publisher comment is a number that
// drifts. What ships is a site; how many pages it has is `DocsCatalog.as`'s business.
const COMMIT_MSG = [
  'demo: publish the web arm as a static site',
  '',
  'Generated by tools/publish-pages.cjs from the `web` arm of ui-demo/: the same',
  'component documentation site the desktop arms render, compiled to WASI and',
  'linked by emcc. Source and the build command live on main.',
].join('\n');

const README = `# asaot.ui — online demo (generated)

This branch is a build output, not a source tree. Do not edit it by hand.

It is the \`web\` arm of \`ui-demo/\` in [RayGyoe/as3compiler-asaotui](https://github.com/RayGyoe/as3compiler-asaotui):
the same component documentation site that the desktop arms render -- one page per
kind, plus the six reference pages about the framework itself -- compiled by
\`as-aot\` to WASI and linked by emcc into a single page.

Source, and the command that reproduces these files:

\`\`\`
git clone https://github.com/RayGyoe/as3compiler-asaotui.git
cd as3compiler-asaotui/ui-demo/air-gallery && ./build.sh web
\`\`\`

\`index.html\` is a byte-identical copy of the generated \`GalleryApp.html\`; only the
filename differs. \`tools/publish-pages.cjs --push\` produced this commit.
`;

function stage() {
  if (!fs.existsSync(SRC)) {
    throw new Error('no build output at ' + SRC + '\nrun: cd ui-demo/air-gallery && ./build.sh web');
  }
  fs.rmSync(STAGE, { recursive: true, force: true });
  const rows = [];
  for (const [from, to] of FILES) {
    const src = path.join(SRC, from);
    // Case-exact on BOTH sides: a case-folding filesystem would happily copy
    // `Arial.ttf` out of a request for `arial.ttf`, and the deployed site would then
    // 404 the name the page actually asks for.
    if (!existsExactly(SRC, from)) throw new Error('missing build output (case-exact): ' + src);
    const dst = path.join(STAGE, to);
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.copyFileSync(src, dst);
    if (!existsExactly(STAGE, to)) throw new Error('staged under a different case than published: ' + to);
    const a = fs.readFileSync(src);
    const b = fs.readFileSync(dst);
    if (sha(a) !== sha(b)) throw new Error('copy not byte-identical: ' + to);
    rows.push({ to, bytes: a.length, sha: sha(a) });
  }
  // Jekyll has nothing to do here, and skipping it keeps .wasm/.data out of its hands.
  fs.writeFileSync(path.join(STAGE, '.nojekyll'), '');
  fs.writeFileSync(path.join(STAGE, 'README.md'), README);
  rows.push({ to: '.nojekyll', bytes: 0, sha: sha(Buffer.alloc(0)) });
  rows.push({ to: 'README.md', bytes: Buffer.byteLength(README), sha: sha(README) });
  for (const r of rows) {
    console.log('  ' + r.to.padEnd(20) + String(r.bytes).padStart(9) + ' B  ' + r.sha.slice(0, 16));
  }
  const total = rows.reduce((n, r) => n + r.bytes, 0);
  console.log('staged ' + rows.length + ' files, ' + (total / 1048576).toFixed(2) + ' MB -> ' + STAGE);
  return rows;
}

// `--serve` mirrors what GitHub Pages does for the paths that matter (no extension
// rewriting, application/wasm for .wasm) so the local check is not a weaker test
// than the deployed one.
function serve(port) {
  const server = http.createServer((req, res) => {
    let rel = decodeURIComponent(req.url.split('?')[0]);
    if (rel === '/' || rel === '') rel = '/index.html';
    const file = path.join(STAGE, path.normalize(rel).replace(/^[\\/]+/, ''));
    if (!file.startsWith(STAGE) || !fs.existsSync(file) || !fs.statSync(file).isFile()) {
      res.writeHead(404, { 'content-type': 'text/plain' });
      res.end('404 ' + rel + '\n');
      console.log('404 ' + rel);
      return;
    }
    const body = fs.readFileSync(file);
    const type = MIME[path.extname(file).toLowerCase()] || 'application/octet-stream';
    res.writeHead(200, { 'content-type': type, 'content-length': body.length, 'cache-control': 'no-store' });
    res.end(body);
    console.log('200 ' + rel + '  ' + type + '  ' + body.length);
  });
  server.listen(port, '127.0.0.1', () => console.log('serving ' + STAGE + ' on http://127.0.0.1:' + port + '/'));
}

// `--check` is the only evidence that the deployed site still equals the build in
// this tree. Comparing bytes (not status codes) is the point: a 200 with a stale
// 7 MB wasm looks exactly like a 200 with the right one.
async function check() {
  const rows = [];
  let bad = 0;
  for (const [from, to] of [['GalleryApp.html', 'index.html'], ...FILES.slice(1)]) {
    const local = fs.readFileSync(path.join(SRC, from));
    const r = await fetch(SITE + to.replace(/\\/g, '/'), { headers: { 'cache-control': 'no-cache' } });
    const body = Buffer.from(await r.arrayBuffer());
    const same = r.ok && sha(body) === sha(local);
    if (!same) bad++;
    rows.push({ to, status: r.status, type: r.headers.get('content-type') || '', live: body.length, local: local.length, same });
    console.log(
      (same ? 'OK   ' : 'DIFF ') +
        String(r.status).padEnd(4) +
        to.padEnd(20) +
        String(body.length).padStart(9) +
        ' B live / ' +
        String(local.length).padStart(9) +
        ' B built  ' +
        (r.headers.get('content-type') || '')
    );
  }
  console.log(bad === 0 ? 'pages check PASS (' + rows.length + ' files byte-identical)' : 'pages check FAIL (' + bad + ' differ)');
  if (bad) process.exitCode = 1;
}

// Plumbing, not `git checkout --orphan gh-pages`: this working tree carries 5.4 GB of
// ignored build output, and switching branches would rewrite every tracked file under
// it. hash-object -> mktree -> commit-tree -> update-ref touches the object database
// and one ref, nothing else.
function makeTree(dir, prefix) {
  const entries = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? prefix + '/' + e.name : e.name;
    entries.push({ name: e.name, dir: e.isDirectory(), rel, abs: path.join(dir, e.name), key: e.isDirectory() ? e.name + '/' : e.name });
  }
  // git sorts tree entries byte-wise on the name, trees as if the name ended in '/'.
  entries.sort((a, b) => (Buffer.from(a.key) < Buffer.from(b.key) ? -1 : 1));
  const lines = entries.map((e) =>
    e.dir ? '040000 tree ' + makeTree(e.abs, e.rel) + '\t' + e.name : '100644 blob ' + git(['hash-object', '-w', e.abs]) + '\t' + e.name
  );
  return git(['mktree'], lines.join('\n') + '\n');
}

// The commit has to be a DESCENDANT of what is already on the remote, or the push is
// rejected as non-fast-forward. A fresh clone has no local `gh-pages` ref at all --
// only `origin/gh-pages` -- so looking at the local ref alone makes every publisher's
// commit an ORPHAN whose parent is nothing, i.e. a rewrite of published history that
// git refuses (measured: `! [rejected] gh-pages -> gh-pages (non-fast-forward)` while
// `refs/remotes/origin/gh-pages` was three commits ahead of an empty local branch).
// So: local ref first, then the remote-tracking one, and orphan only when neither
// exists (a genuinely first publish).
function existingHead() {
  for (const ref of ['refs/heads/' + BRANCH, 'refs/remotes/origin/' + BRANCH]) {
    try {
      return git(['rev-parse', '--verify', ref]);
    } catch { /* try the next source of truth */ }
  }
  return '';
}

function push() {
  const tree = makeTree(STAGE, '');
  const head = existingHead();
  if (head && git(['rev-parse', head + '^{tree}']) === tree) {
    console.log('tree ' + tree.slice(0, 10) + ' already on ' + BRANCH + ' -- nothing to publish');
  } else {
    // `head` is the local ref, the remote tip, or '' for a branch that exists nowhere
    // (only then is an orphan commit what a first publish wants).
    const args = ['commit-tree', tree];
    if (head) args.push('-p', head);
    args.push('-m', COMMIT_MSG);
    const commit = git(args);
    git(['update-ref', 'refs/heads/' + BRANCH, commit]);
    console.log('commit ' + commit.slice(0, 10) + ' on ' + BRANCH);
  }
  git(['push', 'origin', 'refs/heads/' + BRANCH + ':refs/heads/' + BRANCH]);
  console.log('pushed ' + BRANCH + ' -> ' + SITE);
}

const argv = process.argv.slice(2);
if (argv.includes('--check')) {
  check();
} else {
  stage();
  if (argv.includes('--serve')) serve(parseInt(argv[argv.indexOf('--serve') + 1] || '8123', 10));
  else if (argv.includes('--push')) push();
}